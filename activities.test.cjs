const assert=require('node:assert/strict');require('./activities.js');
const {ActivityPlanner,target}=globalThis.DVActivities;
const state={enabled:true,ready:true,online:true,connected:true,visible:true,mode:'mining',inActivity:true};
const planner=new ActivityPlanner();
assert.equal(planner.decide({...state,inHub:true,activityUnlocked:true},5000).type,'travelActivity');
assert.equal(planner.decide({...state,targetCollided:true},7000).type,'interact');
assert.equal(planner.decide({...state,mode:'hunting',inBattle:true},8000).type,'combat');
assert.equal(planner.decide({...state,questReady:true},9000),null,'delivery must take priority over collecting');
assert.equal(planner.decide({...state,online:false},9000),null,'offline operations forbidden');
assert.equal(planner.decide({...state,mode:'boss',slider:{visible:true}},9000),null,'boss slider uses timing engine');
assert.equal(planner.decide({...state,resultOpen:true},9000).type,'activityResult');
const entity=(x,extra={})=>({body:{x,y:0,width:10,height:10},enabled:true,canInteract:true,...extra});
const vein=entity(40),cart=entity(80),player=entity(0);
const level={managers:{entity:{player,entities:[]},mining:{mining:{veins:[vein],cart:{...cart,canInteract:false}}}}};
assert.equal(target(level,'mining'),vein);
level.managers.mining.mining.cart=cart;vein.canInteract=false;
assert.equal(target(level,'mining'),cart,'carry stage must head toward active deposit cart');
cart.id=91;vein.id=92;vein.canInteract=true;
const nextVein=entity(20,{id:93});
level.managers.mining.mining.veins=[vein,nextVein];cart.canInteract=false;
assert.equal(target(level,'mining',()=>true,92),vein,'retain a valid chosen vein even if another becomes closer');
vein.canInteract=false;
assert.equal(target(level,'mining',()=>true,92),nextVein,'a depleted vein must not retain the target lock');
cart.canInteract=true;
assert.equal(target(level,'mining',()=>true,93),cart,'deposit stage must override a previous vein lock');
assert.equal(target(level,'mining',e=>e.id!==91,93),undefined,'blocked carts must not redirect a carried gem back to a vein');
const monster=entity(30),dead=entity(5,{isDead:true});player.inBattle=true;
level.managers.hunting={hunting:{battleMonsters:[dead,monster]}};
assert.equal(target(level,'hunting'),monster);
level.managers.entity.entities=[entity(10,{status:'fail'}),entity(20,{status:'success'})];
assert.equal(target(level,'treasury').status,'success');
console.log('PASS: mining stages, live combat targets, quest priority, boss slider and treasury selection');

assert.equal(planner.decide({...state,mode:'boss',inBattle:false},10000).type,'wait','never chase during boss phase transition');
assert.equal(planner.decide({...state,mode:'boss',inBattle:true},10000).type,'combat');
level.managers.boss={boss:{boss:entity(20,{isDead:true})}};
assert.equal(target(level,'boss'),null,'ignore defeated bosses');
const chest=entity(20,{status:'success',id:100});
const npc=entity(5,{properties:{get:()=>[{name:'cutscene',value:'treasury_room'}]}});
level.managers.entity.entities=[chest,npc];
level.getWorldData=()=>({services:{treasury:{isActiveValue:true}}});
assert.equal(target(level,'treasury',()=>false),null,'during a challenge do not return to the start NPC when a chest is blocked');
assert.equal(target(level,'treasury',()=>true,100),chest);

assert.equal(planner.decide({...state,mode:'hunting',slider:{visible:true}},11000),null,'finish the current fishing slider before switching modes');

const stockPolicy=globalThis.DVActivities.stockPolicy;
const stocks=(suffix,quantity)=>['BLUE','RED','GREEN','YELLOW'].map(color=>({name:color+'_'+suffix,quantity}));
assert.equal(stockPolicy('mining',stocks('GEM',40),{quantity:10}).ready,false,'exactly four times must not trigger');
assert.equal(stockPolicy('mining',stocks('GEM',41),{quantity:10}).ready,true);
assert.equal(stockPolicy('fishing',stocks('FISH',41).slice(1),{quantity:10}).ready,false,'missing resource counts as zero');
assert.equal(stockPolicy('hunting',stocks('HERB',41).map((r,i)=>({...r,quantity:i===2?39:41})),{quantity:10}).ready,false,'every type must exceed its threshold');
assert.equal(stockPolicy('mining',stocks('GEM',100),null).ready,false,'unknown quest never invents a requirement');
console.log('PASS: all resource types and strict four-times delivery threshold');

const {vipFishing}=globalThis.DVActivities;
const boat=entity(20,{label:'npc_hvu_boat'});
const vipLevel={managers:{entity:{player,entities:[boat]}}};
const svc={player:{bpFishingPass:()=>true},tiledState:{getAll:()=>[]}};
assert.equal(vipFishing(vipLevel,svc,{overall_level:{level:49}}).boat,null);
assert.equal(vipFishing(vipLevel,svc,{overall_level:{level:50}}).boat,boat);
assert.equal(vipFishing(vipLevel,{...svc,player:{bpFishingPass:()=>false}},{overall_level:{level:50}}).eligible,false);
svc.tiledState.getAll=()=>['in_hvu_fishing_area'];
assert.equal(vipFishing(vipLevel,svc,{overall_level:{level:50}}).inside,true);
require('./planner.js');
